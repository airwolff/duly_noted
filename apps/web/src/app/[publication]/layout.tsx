import Link from 'next/link';
import type { ReactNode } from 'react';
import { getSupabaseServerClient } from '@/lib/supabase-server.js';
import { resolvePublication } from '@/lib/resolvers.js';

export const runtime = 'edge';

export default async function PublicationLayout({
  children,
  params,
}: {
  children: ReactNode;
  params: Promise<{ publication: string }>;
}) {
  const { publication: pubSlug } = await params;
  const supabase = await getSupabaseServerClient();
  // Pages resolve the publication again and 404 on their own; the layout only
  // needs the name for the masthead, so a miss here just renders it bare.
  const publication = await resolvePublication(supabase, pubSlug);
  const home = `/${pubSlug}`;

  return (
    <div className="flex min-h-screen flex-col">
      <header className="border-b border-stone-200 bg-white">
        <div className="mx-auto flex max-w-3xl flex-wrap items-center justify-between gap-3 px-4 py-4 sm:px-8">
          <Link href={home} className="group flex items-baseline gap-2">
            <span className="font-serif text-2xl font-bold tracking-tight text-stone-900">
              Duly Noted
            </span>
            {publication && (
              <span className="text-sm text-stone-500 group-hover:text-stone-700">
                for {publication.name}
              </span>
            )}
          </Link>
          <form action={`${home}/search`} method="GET" role="search" className="w-full sm:w-64">
            <input
              type="search"
              name="q"
              placeholder="Search meetings…"
              aria-label="Search meetings"
              className="w-full rounded-md border border-stone-300 bg-stone-50 px-3 py-1.5 text-sm placeholder:text-stone-400 focus:border-blue-700 focus:bg-white focus:outline-none focus:ring-1 focus:ring-blue-700"
            />
          </form>
        </div>
      </header>
      <div className="flex-1">{children}</div>
      <footer className="border-t border-stone-200 bg-white">
        <p className="mx-auto max-w-3xl px-4 py-6 text-sm leading-relaxed text-stone-500 sm:px-8">
          Summaries and agenda breakdowns are generated by AI from public meeting video. They can
          contain mistakes; every item links to the moment in the recording so you can check it.
        </p>
      </footer>
    </div>
  );
}
